(function () {
  const RTL_LANGS = ["ar"];
  const STORAGE_KEY = "cgg-lang";

  function cggEach(list, fn) {
    for (let i = 0; i < list.length; i++) fn(list[i], i);
  }

  function applyLanguage(lang) {
    const dict = CGG_TRANSLATIONS[lang] || CGG_TRANSLATIONS.en;
    cggEach(document.querySelectorAll("[data-i18n]"), (el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) el.innerHTML = dict[key];
    });
    const isRtl = RTL_LANGS.indexOf(lang) !== -1;
    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("dir", isRtl ? "rtl" : "ltr");
    document.body.classList.toggle("lang-ar", lang === "ar");
    document.body.classList.toggle("lang-id", lang === "id");
    cggEach(document.querySelectorAll(".lang-switch button"), (btn) => {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
  }

  document.addEventListener("DOMContentLoaded", () => {
    let saved = "en";
    try { saved = localStorage.getItem(STORAGE_KEY) || "en"; } catch (e) {}
    applyLanguage(saved);

    cggEach(document.querySelectorAll(".lang-switch button"), (btn) => {
      btn.addEventListener("click", () => applyLanguage(btn.getAttribute("data-lang")));
    });
  });
})();
